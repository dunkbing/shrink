#!/usr/bin/env bun
// Writes packages/engine/src/formats/index.ts from every *.format.ts file there (each exports `formats: Format[]`),
// so adding a format family never touches a shared file. Run by `bun run gen`.
import { readdirSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dir, "..", "packages/engine/src/formats");
const files = readdirSync(dir).filter((f) => f.endsWith(".format.ts")).sort();
const names = files.map((f) => f.replace(/\.format\.ts$/, "").replace(/[^a-zA-Z0-9]/g, "_"));
const out = `// Generated by scripts/gen-formats.ts: do not edit.
import type { Format } from "../types";
${files.map((f, i) => `import { formats as f_${names[i]} } from "./${f.replace(/\.ts$/, "")}";`).join("\n")}

/** Every format the engine can optimise, in detection order. */
export const allFormats: Format[] = [${names.map((n) => `...f_${n}`).join(", ")}];
`;
await Bun.write(join(dir, "index.ts"), out);
console.log(`${files.length} format files: ${files.join(", ")}`);
